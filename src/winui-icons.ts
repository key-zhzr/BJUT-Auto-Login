const SVG_GEOMETRY_ATTRS = new Set([
  'xmlns',
  'width',
  'height',
  'viewbox',
  'fill',
  'stroke',
  'stroke-width',
  'stroke-linecap',
  'stroke-linejoin',
  'data-icon-engine',
  'data-icon-name',
  'class',
]);

const templateCache = new Map<string, SVGSVGElement>();

function getFluentSvgTemplate(name: string): SVGSVGElement | null {
  const cached = templateCache.get(name);
  if (cached) return cached;

  const raw = FLUENT_SVG_MAP[name];
  if (!raw) return null;

  const holder = document.createElement('div');
  holder.innerHTML = raw.trim();
  const svg = holder.firstElementChild;
  if (!(svg instanceof SVGSVGElement)) return null;

  templateCache.set(name, svg);
  return svg;
}

function collectIconTargets(root: Element | Document | DocumentFragment): Element[] {
  const elements: Element[] = [];
  if (root instanceof Element && root.hasAttribute('data-lucide')) {
    elements.push(root);
  }
  elements.push(...Array.from(root.querySelectorAll('[data-lucide]')));
  return elements;
}

function buildFluentSvg(source: Element, name: string): SVGSVGElement | null {
  const template = getFluentSvgTemplate(name);
  if (!template) return null;

  const svg = template.cloneNode(true) as SVGSVGElement;
  for (const attr of Array.from(source.attributes)) {
    const lower = attr.name.toLowerCase();
    if (SVG_GEOMETRY_ATTRS.has(lower)) continue;
    svg.setAttribute(attr.name, attr.value);
  }

  const keptClasses = Array.from(source.classList).filter(
    cls => cls !== 'lucide' && !cls.startsWith('lucide-') && cls !== 'fluent-icon' && !cls.startsWith('fluent-icon-'),
  );
  svg.setAttribute('class', ['fluent-icon', `fluent-icon-${name}`, ...keptClasses].join(' '));
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('data-lucide', name);
  svg.setAttribute('data-icon-name', name);
  svg.setAttribute('data-icon-engine', 'fluent');
  if (!svg.hasAttribute('aria-label') && !svg.hasAttribute('aria-labelledby')) {
    svg.setAttribute('aria-hidden', 'true');
  }
  return svg;
}

function createLucidePlaceholder(source: Element, name: string): HTMLElement {
  const placeholder = document.createElement('i');
  for (const attr of Array.from(source.attributes)) {
    const lower = attr.name.toLowerCase();
    if (SVG_GEOMETRY_ATTRS.has(lower)) continue;
    placeholder.setAttribute(attr.name, attr.value);
  }
  const keptClasses = Array.from(source.classList).filter(
    cls => cls !== 'lucide' && !cls.startsWith('lucide-') && cls !== 'fluent-icon' && !cls.startsWith('fluent-icon-'),
  );
  if (keptClasses.length) placeholder.setAttribute('class', keptClasses.join(' '));
  placeholder.setAttribute('data-lucide', name);
  return placeholder;
}

function renderSingleLucideFallback(source: Element, lucideIcons: Record<string, IconNode>) {
  const holder = document.createElement('span');
  const placeholder = source.tagName.toLowerCase() === 'i'
    ? (source.cloneNode(false) as HTMLElement)
    : createLucidePlaceholder(source, source.getAttribute('data-lucide') || '');
  holder.append(placeholder);
  createIcons({ icons: lucideIcons, root: holder });
  const rendered = holder.firstElementChild;
  if (rendered && rendered.tagName.toLowerCase() === 'svg') {
    const name = rendered.getAttribute('data-lucide') || '';
    rendered.setAttribute('data-icon-name', name);
    rendered.setAttribute('data-icon-engine', 'lucide');
    source.replaceWith(rendered);
  }
}

export function renderThemeIcons(
  root: Element | Document | DocumentFragment = document,
  lucideIcons: Record<string, IconNode>,
): void {
  const isWinui = document.documentElement.dataset.theme === 'winui';
  const targets = collectIconTargets(root);
  if (!targets.length) return;

  if (isWinui) {
    for (const el of targets) {
      const name = el.getAttribute('data-lucide')?.trim() || '';
      if (!name) continue;
      if (
        el.tagName.toLowerCase() === 'svg'
        && el.getAttribute('data-icon-name') === name
        && el.getAttribute('data-icon-engine') === (FLUENT_SVG_MAP[name] ? 'fluent' : 'lucide')
      ) {
        continue;
      }
      const fluentSvg = buildFluentSvg(el, name);
      if (fluentSvg) {
        el.replaceWith(fluentSvg);
      } else {
        renderSingleLucideFallback(el, lucideIcons);
      }
    }
    return;
  }

  let hasPlaceholderDescendants = false;
  for (const el of targets) {
    const name = el.getAttribute('data-lucide')?.trim() || '';
    if (!name) continue;
    if (
      el.tagName.toLowerCase() === 'svg'
      && el.getAttribute('data-icon-engine') === 'lucide'
      && el.getAttribute('data-icon-name') === name
    ) {
      continue;
    }
    if (el === root) {
      renderSingleLucideFallback(el, lucideIcons);
      continue;
    }
    if (el.tagName.toLowerCase() === 'svg' && el.getAttribute('data-icon-engine') === 'fluent') {
      const placeholder = createLucidePlaceholder(el, name);
      el.replaceWith(placeholder);
    }
    hasPlaceholderDescendants = true;
  }

  if (hasPlaceholderDescendants) {
    const lucideRoot: Element | Document =
      root instanceof DocumentFragment ? document : root;
    // DocumentFragments with placeholders can render safely per-child or when attached.
    if (root instanceof DocumentFragment) {
      for (const el of collectIconTargets(root)) {
        const name = el.getAttribute('data-lucide')?.trim() || '';
        if (
          el.tagName.toLowerCase() === 'svg'
          && el.getAttribute('data-icon-engine') === 'lucide'
          && el.getAttribute('data-icon-name') === name
        ) {
          continue;
        }
        renderSingleLucideFallback(el, lucideIcons);
      }
    } else {
      createIcons({ icons: lucideIcons, root: lucideRoot });
      for (const el of collectIconTargets(lucideRoot)) {
        if (el.tagName.toLowerCase() === 'svg' && el.getAttribute('data-icon-engine') !== 'fluent') {
          el.setAttribute('data-icon-name', el.getAttribute('data-lucide') || '');
          el.setAttribute('data-icon-engine', 'lucide');
        }
      }
    }
  }
}

export function refreshAllThemeIcons(lucideIcons: Record<string, IconNode>): void {
  renderThemeIcons(document, lucideIcons);
}
